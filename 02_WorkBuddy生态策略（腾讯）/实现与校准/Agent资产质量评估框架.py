def callout(text, color=PURPLE_600):
    """强调框：灰色底描边文本框效果，用段落底纹模拟"""
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_before = Pt(8)
    pf.space_after = Pt(8)
    pf.left_indent = Pt(12)
    pf.right_indent = Pt(12)
    pf.line_spacing = 1.5
    set_run(p.add_run(text), size=12, color=color, bold=True)
    # 加左边框强调
    pPr = p._p.get_or_add_pPr()
    pbdr = OxmlElement("w:pBdr")
    left = OxmlElement("w:left")
    left.set(qn("w:val"), "single")
    left.set(qn("w:sz"), "12")
    left.set(qn("w:space"), "8")
    left.set(qn("w:color"), "534AB7")
    pbdr.append(left)
    pPr.append(pbdr)
    return p


def add_table(headers, rows, col_widths=None, header_color=BLUE_600):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, htext in enumerate(headers):
        hdr[i].text = ""
        p = hdr[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        set_run(p.add_run(htext), font=HEI, size=10.5, color=RGBColor(0xFF, 0xFF, 0xFF), bold=True)
        shd = OxmlElement("w:shd")
        shd.set(qn("w:fill"), "185FA5")
        hdr[i]._tc.get_or_add_tcPr().append(shd)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            set_run(p.add_run(str(val)), size=10.5)
    if col_widths:
        for i, wd in enumerate(col_widths):
            for row in t.rows:
                row.cells[i].width = Cm(wd)
    # 表后加一点空隙
    sp = doc.add_paragraph()
    sp.paragraph_format.space_after = Pt(4)
    return t


